#!/usr/bin/env node
/**
 * Pre-renders the Start Page studio picks (src/config/start-page-picks.js) to static SVGs so a first-run cover
 * does not run seven synchronous engine renders on the main thread.
 *
 *   npm run start-page:picks           write assets/start-page/picks/<preset-id>.svg + src/config/start-page-picks-art.js
 *   npm run start-page:picks -- --check  exit 1 when a file is missing or a manifest hash is stale (no writes)
 *
 * It drives the same StartPageArtRenderer the live page uses, in the same jsdom runtime the tests use, so the
 * output is the art the live render would produce. Run it after editing a pick's preset, the pick list, or
 * anything that changes how a preset renders (then bump RENDER_VERSION in art-source.js too).
 */
const fs = require('fs');
const path = require('path');
const { loadVecturaRuntime } = require('../tests/helpers/load-vectura-runtime');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'start-page', 'picks');
const MANIFEST = path.join(ROOT, 'src', 'config', 'start-page-picks-art.js');
const WEB_PATH = './assets/start-page/picks/';

// Lossless size trim: drop trailing zeros from the numbers inside path data ("113.500" -> "113.5", "5.000" -> "5").
const trimPathNumbers = (svg) => svg.replace(/\bd="([^"]*)"/g, (_m, d) => `d="${d.replace(/(\d+)\.(\d*?)0+(?=[ "A-Za-z,-])/g, (_n, i, f) => (f ? `${i}.${f}` : i))}"`);

const manifestSource = (version, hashByPick) => `/**
 * Start Page pre-rendered picks manifest — window.Vectura.START_PAGE_PICKS_ART.
 * GENERATED by \`npm run start-page:picks\` (scripts/build-start-page-picks.js); do not hand-edit.
 * hashByPick[id] is the content hash of that bundled preset when its SVG was rendered; art-source.js uses
 * ${WEB_PATH}<id>.svg only while the hash still matches the current preset (and \`version\` matches RENDER_VERSION).
 */
(() => {
  const G = (typeof window !== 'undefined' ? window : globalThis);
  const Vectura = G.Vectura = G.Vectura || {};
  Vectura.START_PAGE_PICKS_ART = Object.freeze({
    version: ${JSON.stringify(version)},
    path: ${JSON.stringify(WEB_PATH)},
    hashByPick: Object.freeze(${JSON.stringify(hashByPick, null, 2).replace(/\n/g, '\n    ')}),
  });
})();
`;

const main = async () => {
  const check = process.argv.includes('--check');
  const runtime = await loadVecturaRuntime({ includeRenderer: true, includeUi: true, includeApp: true, includeMain: false, useIndexHtml: true });
  try {
    const V = runtime.window.Vectura;
    const Source = V.StartPageArtSource;
    const picks = V.START_PAGE_PICKS.STUDIO_PICKS;
    const byId = new Map(V.PRESETS.map((p) => [p.id, p]));
    const hashByPick = {};
    const svgs = {};
    for (const id of picks) {
      const preset = byId.get(id);
      if (!preset) throw new Error(`Pick "${id}" is not a bundled preset`);
      hashByPick[id] = Source.hashOf(preset);
      if (check) continue;
      const out = await V.StartPageArtRenderer.renderPreset(preset);
      svgs[id] = trimPathNumbers(out.svg);
    }
    if (check) {
      const current = V.START_PAGE_PICKS_ART;
      const bad = picks.filter((id) => !current || current.hashByPick[id] !== hashByPick[id]
        || !fs.existsSync(path.join(OUT_DIR, `${id}.svg`)));
      if (bad.length || (current && current.version !== Source.RENDER_VERSION)) {
        console.error(`Stale pre-rendered picks (${bad.join(', ') || 'render version'}). Run: npm run start-page:picks`);
        process.exitCode = 1;
      }
      return;
    }
    fs.mkdirSync(OUT_DIR, { recursive: true });
    const keep = new Set(picks.map((id) => `${id}.svg`));
    fs.readdirSync(OUT_DIR).filter((f) => f.endsWith('.svg') && !keep.has(f)).forEach((f) => fs.unlinkSync(path.join(OUT_DIR, f)));
    let total = 0;
    for (const id of picks) {
      fs.writeFileSync(path.join(OUT_DIR, `${id}.svg`), svgs[id]);
      total += Buffer.byteLength(svgs[id]);
      console.log(`${id}.svg  ${(Buffer.byteLength(svgs[id]) / 1024).toFixed(1)} KB`);
    }
    fs.writeFileSync(MANIFEST, manifestSource(Source.RENDER_VERSION, hashByPick));
    console.log(`${picks.length} picks, ${(total / 1024).toFixed(1)} KB total -> assets/start-page/picks/, src/config/start-page-picks-art.js`);
  } finally {
    runtime.cleanup();
  }
};

main().then(() => process.exit(process.exitCode || 0), (err) => { console.error(err); process.exit(1); });
